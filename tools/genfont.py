"""Generate src/font.h: an antialiased Latin-1 glyph atlas for UI text.

Run once at development time (needs Pillow). The source font is DejaVu Sans
Mono (Bitstream Vera / public-domain derived licence, free to embed).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SRC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
SIZE = 15
font = ImageFont.truetype(SRC, SIZE)
ascent, descent = font.getmetrics()
W = round(font.getlength('M'))
H = ascent + descent
chars = list(range(32, 127)) + list(range(160, 256))
out = ['/* Generated by tools/genfont.py from DejaVu Sans Mono; do not edit. */',
       '#pragma once', f'#define FONT_W {W}', f'#define FONT_H {H}',
       f'#define FONT_FIRST_HI 160',
       f'static const unsigned char font_glyphs[{len(chars)}][{W*H}] = {{']
for c in chars:
    im = Image.new('L', (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
    out.append('  {' + ','.join(str(v) for v in im.tobytes()) + '},')
out.append('};')
open('src/font.h', 'w').write('\n'.join(out) + '\n')
print(W, H, len(chars))
